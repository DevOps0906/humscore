import { expect, openKeysInput, test } from "./fixtures";

for (const width of [390, 900, 1440]) test(`${width}px 빈 템플릿과 제작자 개별 행 및 악보 탭`, async ({ page }) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width, height: 1000 });
  await openKeysInput(page);
  await page.getByRole("button", { name: "템플릿으로 시작하기", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: /밴드 스코어/ }).click();
  const left = await dialog.getByRole("region", { name: "악보 형식 선택" }).boundingBox();
  const right = await dialog.getByRole("region", { name: "템플릿 미리보기" }).boundingBox();
  expect(right!.x).toBeGreaterThan(left!.x + left!.width - 1);
  await page.screenshot({ path: `.nomad/task-028/${width}-template.png`, fullPage: true });
  await dialog.getByRole("button", { name: "다음", exact: true }).click();
  await dialog.getByRole("button", { name: "다음", exact: true }).click();
  const fields = ["작사자", "작곡자", "편곡자"];
  const boxes = [];
  for (const [index, label] of fields.entries()) {
    const input = dialog.getByLabel(`템플릿 ${label}`, { exact: true });
    await input.fill(`제작자${index + 1}`);
    boxes.push((await input.boundingBox())!);
  }
  expect(boxes[1].y).toBeGreaterThan(boxes[0].y);
  expect(boxes[2].y).toBeGreaterThan(boxes[1].y);
  await dialog.getByRole("button", { name: "이 템플릿으로 악보 생성", exact: true }).click();
  await expect(page.getByRole("tab", { name: "전체 악보", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.reload();
  await expect(page.getByRole("tab", { name: "전체 악보", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "악보로 저장", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "저장", exact: true }).click();
  await expect(page).toHaveURL(/\/scores\//);
  const score = await page.evaluate(() => JSON.parse(localStorage.getItem("humscore.scores.v1")!)[0]);
  expect(score.notes).toEqual([]);
  expect(score.chords).toEqual([]);
  expect(score.measureCount).toBe(8);
  expect(score.composer).toBe("제작자2");
  expect(score.parts.every((part: { notes: unknown[] }) => part.notes.length === 0)).toBe(true);
  const output = page.locator(".score-export");
  await expect(output.locator("[aria-busy]")).toHaveAttribute("aria-busy", "false");
  const firstLineMeasures = await output.locator("svg").first().locator(".vf-measure").evaluateAll((measures) => {
    const ys = measures.map((measure) => measure.querySelector(":scope > path")!.getBoundingClientRect().top);
    const first = Math.min(...ys);
    return ys.filter((y) => Math.abs(y - first) < 1).length;
  });
  expect(firstLineMeasures).toBe(4);
  const printedCredits = output.locator("[data-score-credits] text");
  await expect(printedCredits).toHaveText(["작사 제작자1", "작곡 제작자2", "편곡 제작자3"]);
  const printYs = await printedCredits.evaluateAll((rows) => rows.map((row) => Number(row.getAttribute("y"))));
  expect(printYs[1]).toBeGreaterThan(printYs[0]);
  expect(printYs[2]).toBeGreaterThan(printYs[1]);
  if (width === 1440) await page.pdf({ path: ".nomad/task-028/credits-a4.pdf", format: "A4", printBackground: true, preferCSSPageSize: true });
  await page.getByRole("tab", { name: "개별 악보", exact: true }).click();
  const credits = page.getByTestId("score-credit-line");
  await expect(credits).toHaveText(["작사 제작자1", "작곡 제작자2", "편곡 제작자3"]);
  const ys = await credits.evaluateAll((rows) => rows.map((row) => row.getBoundingClientRect().y));
  expect(ys[1]).toBeGreaterThan(ys[0]);
  expect(ys[2]).toBeGreaterThan(ys[1]);
  await page.getByRole("group", { name: "편집할 악기 파트" }).getByRole("button", { name: /베이스기타/ }).click();
  await expect(page.getByRole("region", { name: "TAB 악보", exact: true })).toBeVisible();
  await expect(page.locator(".score-sheet:visible")).toHaveCount(0);
  await page.getByRole("button", { name: "악보", exact: true }).click();
  await expect(page.locator(".score-sheet:visible")).toHaveCount(1);
  await expect(page.getByRole("region", { name: "TAB 악보", exact: true })).toBeVisible();
  await expect(page.locator(".score-sheet:visible [aria-busy]")).toHaveAttribute("aria-busy", "false");
  const svg = page.locator(".score-sheet:visible svg").first();
  const size = await svg.boundingBox();
  expect(size!.height).toBeLessThanOrEqual(741);
  expect(size!.width).toBeLessThanOrEqual(width);
});
